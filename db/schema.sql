CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 passwordHash VARCHAR(100) NOT NULL, role ENUM('admin','sale') NOT NULL DEFAULT 'sale', active BOOLEAN NOT NULL DEFAULT TRUE,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 tokenHash CHAR(64) PRIMARY KEY, userId CHAR(36) NOT NULL, expiresAt DATETIME(3) NOT NULL,
 FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE, INDEX (expiresAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_attempts (
 id CHAR(64) PRIMARY KEY, attempts INT NOT NULL DEFAULT 1, windowStart DATETIME(3) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS accounts (
 id CHAR(36) PRIMARY KEY, name VARCHAR(200) NOT NULL, website VARCHAR(500) NOT NULL DEFAULT '',
 region VARCHAR(120) NOT NULL DEFAULT '', market VARCHAR(120) NOT NULL DEFAULT 'Việt Nam',
 segment VARCHAR(120) NOT NULL DEFAULT 'Lữ hành', tier VARCHAR(60) NOT NULL DEFAULT 'Tiêu chuẩn',
 ownerId CHAR(36) NOT NULL, stage VARCHAR(40) NOT NULL DEFAULT 'new', notes TEXT, deletedAt DATETIME(3) NULL,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY (ownerId) REFERENCES users(id), INDEX(ownerId), INDEX(stage)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS contacts (
 id CHAR(36) PRIMARY KEY, accountId CHAR(36) NOT NULL, name VARCHAR(120) NOT NULL DEFAULT '',
 email VARCHAR(254) NOT NULL UNIQUE, title VARCHAR(120) NOT NULL DEFAULT '', language VARCHAR(20) NOT NULL DEFAULT 'vi',
 source VARCHAR(1000) NOT NULL, consentStatus VARCHAR(40) NOT NULL DEFAULT 'unreviewed',
 consentPurpose VARCHAR(500) NOT NULL DEFAULT '', consentEvidence TEXT, consentAt DATETIME(3), reviewedBy CHAR(36),
 country VARCHAR(10) NOT NULL DEFAULT 'VN', lastReplyAt DATETIME(3), lastContactedAt DATETIME(3),
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY(accountId) REFERENCES accounts(id), FOREIGN KEY(reviewedBy) REFERENCES users(id), INDEX(consentStatus)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS consent_events (
 id CHAR(36) PRIMARY KEY, contactId CHAR(36) NOT NULL, actorId CHAR(36), status VARCHAR(40) NOT NULL,
 purpose VARCHAR(500) NOT NULL DEFAULT '', evidence TEXT, createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(contactId) REFERENCES contacts(id), FOREIGN KEY(actorId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id CHAR(36) PRIMARY KEY, name VARCHAR(200) NOT NULL, destination VARCHAR(150) NOT NULL,
 duration VARCHAR(80) NOT NULL, price DECIMAL(16,2) NOT NULL DEFAULT 0, currency VARCHAR(3) NOT NULL DEFAULT 'VND',
 unit VARCHAR(80) NOT NULL DEFAULT 'khách', tier VARCHAR(60) NOT NULL DEFAULT 'Tiêu chuẩn',
 validUntil DATE NOT NULL, conditions TEXT NOT NULL, version INT NOT NULL DEFAULT 1,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS templates (
 id CHAR(36) PRIMARY KEY, name VARCHAR(200) NOT NULL, subject VARCHAR(500) NOT NULL, body TEXT NOT NULL,
 category VARCHAR(80) NOT NULL DEFAULT 'Giới thiệu tuyến', version INT NOT NULL DEFAULT 1,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS campaigns (
 id CHAR(36) PRIMARY KEY, name VARCHAR(200) NOT NULL, ownerId CHAR(36) NOT NULL,
 recipientPolicy VARCHAR(40) NOT NULL DEFAULT 'eligible_only',
 templateId CHAR(36) NOT NULL, productId CHAR(36) NULL, status VARCHAR(40) NOT NULL DEFAULT 'draft',
 subject VARCHAR(500), body TEXT, templateVersion INT, productVersion INT, approvedBy CHAR(36), approvedAt DATETIME(3),
 scheduledAt DATETIME(3), followupBody TEXT, followupDays INT NOT NULL DEFAULT 4,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY(ownerId) REFERENCES users(id), FOREIGN KEY(templateId) REFERENCES templates(id), FOREIGN KEY(productId) REFERENCES products(id),
 FOREIGN KEY(approvedBy) REFERENCES users(id), INDEX(status,scheduledAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS campaign_recipients (
 id CHAR(36) PRIMARY KEY, campaignId CHAR(36) NOT NULL, contactId CHAR(36) NOT NULL, step INT NOT NULL DEFAULT 0,
 status VARCHAR(30) NOT NULL DEFAULT 'pending', dueAt DATETIME(3), messageId VARCHAR(254),
 renderedSubject VARCHAR(500), renderedBody MEDIUMTEXT, attempts INT NOT NULL DEFAULT 0,
 error VARCHAR(1000), sentAt DATETIME(3), claimedAt DATETIME(3), repliedAt DATETIME(3), deliveredAt DATETIME(3),
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(campaignId,contactId,step), UNIQUE(messageId), FOREIGN KEY(campaignId) REFERENCES campaigns(id), FOREIGN KEY(contactId) REFERENCES contacts(id), INDEX(status,dueAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS suppressions (
 id CHAR(36) PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE, reason VARCHAR(100) NOT NULL, actorId CHAR(36),
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(actorId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tasks (
 id CHAR(36) PRIMARY KEY, title VARCHAR(250) NOT NULL, accountId CHAR(36), ownerId CHAR(36) NOT NULL,
 dueAt DATETIME(3) NOT NULL, priority VARCHAR(20) NOT NULL DEFAULT 'normal', status VARCHAR(20) NOT NULL DEFAULT 'open',
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(ownerId) REFERENCES users(id), FOREIGN KEY(accountId) REFERENCES accounts(id), INDEX(ownerId,status,dueAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rfqs (
 id CHAR(36) PRIMARY KEY, accountId CHAR(36) NOT NULL, ownerId CHAR(36) NOT NULL, title VARCHAR(200) NOT NULL,
 destination VARCHAR(150) NOT NULL, departureDate DATE, pax INT NOT NULL DEFAULT 1, budget DECIMAL(16,2) NOT NULL DEFAULT 0,
 status VARCHAR(30) NOT NULL DEFAULT 'new', deadline DATE, notes TEXT, bookingReference VARCHAR(120), revenue DECIMAL(16,2) NOT NULL DEFAULT 0,
 grossMargin DECIMAL(16,2) NOT NULL DEFAULT 0, createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(accountId) REFERENCES accounts(id), FOREIGN KEY(ownerId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS quotes (
 id CHAR(36) PRIMARY KEY, rfqId CHAR(36) NOT NULL, version INT NOT NULL, amount DECIMAL(16,2) NOT NULL,
 currency VARCHAR(3) NOT NULL DEFAULT 'VND', validUntil DATE NOT NULL, conditions TEXT NOT NULL,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), UNIQUE(rfqId,version), FOREIGN KEY(rfqId) REFERENCES rfqs(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS inbound_messages (
 id CHAR(36) PRIMARY KEY, contactId CHAR(36) NOT NULL, subject VARCHAR(500) NOT NULL, body MEDIUMTEXT NOT NULL,
 classification VARCHAR(30) NOT NULL DEFAULT 'unclassified', receivedAt DATETIME(3) NOT NULL,
 FOREIGN KEY(contactId) REFERENCES contacts(id), INDEX(receivedAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, userId CHAR(36), title VARCHAR(250) NOT NULL, body VARCHAR(1000) NOT NULL DEFAULT '',
 kind VARCHAR(40) NOT NULL DEFAULT 'info', readAt DATETIME(3), createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(userId) REFERENCES users(id), INDEX(userId,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id CHAR(36) PRIMARY KEY, actorId CHAR(36), action VARCHAR(120) NOT NULL, entityType VARCHAR(80) NOT NULL,
 entityId VARCHAR(100), details JSON, createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(createdAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notification_reads (
 notificationId BIGINT UNSIGNED NOT NULL, userId CHAR(36) NOT NULL, readAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(notificationId,userId), FOREIGN KEY(notificationId) REFERENCES notifications(id) ON DELETE CASCADE,
 FOREIGN KEY(userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_versions (
 productId CHAR(36) NOT NULL, version INT NOT NULL, snapshot JSON NOT NULL,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), PRIMARY KEY(productId,version),
 FOREIGN KEY(productId) REFERENCES products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 settingKey VARCHAR(120) PRIMARY KEY, value TEXT NOT NULL, updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS webhook_events (
 eventId VARCHAR(200) PRIMARY KEY, type VARCHAR(30) NOT NULL, createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cron_runs (
 id CHAR(36) PRIMARY KEY, status VARCHAR(30) NOT NULL, processed INT NOT NULL DEFAULT 0, details VARCHAR(1000),
 startedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), finishedAt DATETIME(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS import_batches (
 id CHAR(36) PRIMARY KEY, actorId CHAR(36) NOT NULL, filename VARCHAR(250) NOT NULL, imported INT NOT NULL, skipped INT NOT NULL,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(actorId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS import_jobs (
 id CHAR(36) PRIMARY KEY, actorId CHAR(36) NOT NULL, filename VARCHAR(250) NOT NULL, total INT NOT NULL,
 processed INT NOT NULL DEFAULT 0, imported INT NOT NULL DEFAULT 0, skipped INT NOT NULL DEFAULT 0,
 nextChunk INT NOT NULL DEFAULT 0, status ENUM('running','completed') NOT NULL DEFAULT 'running',
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY(actorId) REFERENCES users(id) ON DELETE CASCADE, INDEX(actorId,createdAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS import_chunks (
 jobId CHAR(36) NOT NULL, chunkIndex INT NOT NULL, digest CHAR(64) NOT NULL,
 PRIMARY KEY(jobId,chunkIndex), FOREIGN KEY(jobId) REFERENCES import_jobs(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS mailboxes (
 id CHAR(36) PRIMARY KEY, userId CHAR(36) NOT NULL, provider VARCHAR(20) NOT NULL, email VARCHAR(254) NOT NULL,
 accessToken TEXT NOT NULL, refreshToken TEXT NOT NULL, expiresAt DATETIME(3) NOT NULL, lastSyncAt DATETIME(3),
 lastError VARCHAR(500), UNIQUE(userId), FOREIGN KEY(userId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS oauth_states (
 stateHash CHAR(64) PRIMARY KEY, userId CHAR(36) NOT NULL, provider VARCHAR(20) NOT NULL, expiresAt DATETIME(3) NOT NULL,
 FOREIGN KEY(userId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS private_files (
 id CHAR(36) PRIMARY KEY, parentType ENUM('product','rfq') NOT NULL, parentId CHAR(36) NOT NULL,
 filename VARCHAR(200) NOT NULL, content MEDIUMBLOB NOT NULL, size INT NOT NULL, actorId CHAR(36) NOT NULL,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(actorId) REFERENCES users(id),
 INDEX(parentType,parentId)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ai_threads (
 id CHAR(36) PRIMARY KEY, userId CHAR(36) NOT NULL, title VARCHAR(160) NOT NULL,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updatedAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 FOREIGN KEY(userId) REFERENCES users(id) ON DELETE CASCADE, INDEX(userId,updatedAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ai_requests (
 id CHAR(36) PRIMARY KEY, userId CHAR(36) NOT NULL, threadId CHAR(36) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'running',
 error VARCHAR(500), model VARCHAR(100), inputTokens INT NOT NULL DEFAULT 0, outputTokens INT NOT NULL DEFAULT 0,
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), finishedAt DATETIME(3),
 FOREIGN KEY(userId) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(threadId) REFERENCES ai_threads(id) ON DELETE CASCADE,
 INDEX(userId,createdAt), INDEX(threadId,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ai_messages (
 id CHAR(36) PRIMARY KEY, threadId CHAR(36) NOT NULL, requestId CHAR(36) NOT NULL, role ENUM('user','assistant') NOT NULL,
 content MEDIUMTEXT NOT NULL, metadata JSON, createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(threadId) REFERENCES ai_threads(id) ON DELETE CASCADE, FOREIGN KEY(requestId) REFERENCES ai_requests(id) ON DELETE CASCADE,
 UNIQUE(requestId,role), INDEX(threadId,createdAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ai_drafts (
 id CHAR(36) PRIMARY KEY, userId CHAR(36) NOT NULL, messageId CHAR(36) NOT NULL, kind VARCHAR(30) NOT NULL, payload JSON NOT NULL,
 status ENUM('pending','applied') NOT NULL DEFAULT 'pending', entityId CHAR(36), appliedAt DATETIME(3),
 createdAt TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(userId) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(messageId) REFERENCES ai_messages(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS direct_mail_batches (
 id CHAR(36) PRIMARY KEY, ownerId CHAR(36) NOT NULL, requestId CHAR(36) NOT NULL, payloadHash CHAR(64) NOT NULL,
 name VARCHAR(200) NOT NULL, subject VARCHAR(500) NOT NULL, body TEXT NOT NULL, recipientPolicy VARCHAR(40) NOT NULL,
 productSnapshot JSON, senderName VARCHAR(120) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'queued',
 createdAt DATETIME(3) NOT NULL DEFAULT (UTC_TIMESTAMP(3)), finishedAt DATETIME(3),
 UNIQUE(ownerId,requestId), FOREIGN KEY(ownerId) REFERENCES users(id), INDEX(status,createdAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS direct_mail_recipients (
 id CHAR(36) PRIMARY KEY, batchId CHAR(36) NOT NULL, contactId CHAR(36), email VARCHAR(254) NOT NULL,
 accountName VARCHAR(200) NOT NULL DEFAULT '', status VARCHAR(30) NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0, messageId VARCHAR(254), error VARCHAR(1000),
 renderedSubject VARCHAR(500), renderedBody MEDIUMTEXT, claimedAt DATETIME(3), sentAt DATETIME(3),
 retryAuthorizedAt DATETIME(3), retryAuthorizedBy CHAR(36), retryReason VARCHAR(2000), retryConsumedBy CHAR(36),
 FOREIGN KEY(batchId) REFERENCES direct_mail_batches(id), FOREIGN KEY(contactId) REFERENCES contacts(id) ON DELETE SET NULL,
 UNIQUE(batchId,email), UNIQUE(messageId), INDEX(status), INDEX(contactId,status), INDEX direct_email_status(email,status)
) ENGINE=InnoDB;
